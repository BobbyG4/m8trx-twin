/**
 * One store-day of history, generated by the SAME stack `scenarioSelfTest` and `connectDayDrive` use:
 * [TrafficGenerator] arrivals off the model's hourly curve → [Journeys] (browse / buy / try-on / shoplift)
 * → 5 Hz dwell streams → [ImpressionOracle]. Nothing is published; the day is reduced to the aggregates the
 * history files carry and then discarded.
 *
 * The one structural difference from `ScenarioRun` is the sink: a whole day of samples (~1.1 M at Denver)
 * is never held. [OracleSink] buffers ONE shopper's stream and runs the oracle the moment the journey
 * evicts that shopper (journeys emit every sample before `finish()` evicts), so memory is one session deep
 * and the verdict is identical — `ScenarioRun` also runs the oracle per shopper stream.
 *
 * Attribution rules (all stated in the RESULTS file):
 *  - A shopper's visit, transaction and session dwell land in the hour they ARRIVED (a cohort view), which
 *    is what guarantees `conversion_rate = transactions / visits <= 1` in every hourly row.
 *  - Money is tallied in integer CENTS, so department sums equal store sums exactly.
 *  - A department's units/value are by line; its `transaction_count` is by the basket's PRIMARY department
 *    (highest-value line), so department transactions also sum exactly to the store's.
 *  - Department traffic = shoppers with at least one oracle impression at a fixture whose `in_area_zone` is
 *    that region; its dwell = those impressions' durations (seconds) per visiting shopper.
 *  - `transit_count` = sessions shorter than [TRANSIT_MAX_MS] (5 min) — walked through rather than shopped.
 *  - Fixture `impression` = distinct shoppers with an impression there; `dwell` = sum of impression
 *    durations (s); `engagement` = units picked up there (bought lines + concealed units).
 */
class HistoryDayRunner(
    val store: ChainKeys.Store,
    private val baseModel: OperatingModel,
    chainDir: Path,
    /** the seasonal department factors on a date (the story's), so the ATV can be held level through the year */
    private val seasonalWeights: (LocalDate) -> Map<String, Double> = { emptyMap() },
) {
    private val log = LoggerFactory.getLogger(HistoryDayRunner::class.java)
    private val layout = chainDir.resolve("stores/${store.slug}/layout.json")
    private val fixtures: FixtureSet = FixtureSet.load(layout)
    private val zones = ZoneRoleResolver.resolve(layout).zones
    private val catalog: StoreCatalog = StoreCatalog.load(chainDir.resolve("stores/${store.slug}/assortment.csv"))
    private val gates = EasTagging.loadGates(layout)
    private val oracle = ImpressionOracle()

    /** fixture code → region zone code it physically sits in (only where that is a region of this store). */
    private val fixtureRegion: Map<String, String> = run {
        val regionCodes = store.regions.map { it.code }.toSet()
        fixtures.fixtures.mapNotNull { f -> f.inAreaZone?.takeIf { it in regionCodes }?.let { f.code to it } }.toMap()
    }

    /** Fixture codes that both the pipeline can see AND the key export carries — the behavioral rows. */
    val behavioralFixtures: List<String> = run {
        val keyed = store.fixtures.map { it.code }.toSet()
        fixtures.impressionVisible.map { it.code }.filter { it in keyed }.sorted()
    }

    val taggedSkuCount: Int get() = catalog.taggedSkus().size

    /**
     * Sampler targets that make the EXISTING basket sampler land on the operating model's own numbers.
     *
     * [StoreCatalog.sampleBasket] draws `round(units_per_txn + U(-0.8, 0.8))` units — mean 2.25 for the
     * model's 2.2 — and nearest-priced SKUs around `avg_line_price_usd`, whose realised mean depends on each
     * store's catalog (it ran $60–62 ATV against the model's $58 in the first trial). Rather than touch the
     * sampler, the history hands it calibrated TARGETS: the unit target whose rounded mean is exactly the
     * model's `units_per_txn`, and per store the line-price target whose realised mean is
     * `atv_usd / units_per_txn` (three fixed-seed Monte-Carlo passes of 20,000 baskets). Same sampler, same
     * catalog, same price-band shape — the year simply ties out to $58 an order.
     */
    val samplerUnitTarget: Double = solveUnitTarget(baseModel.basket.unitsPerTxn.value)

    /**
     * The department mix and the line price target are solved TOGETHER: the department weights move which
     * SKUs get sold (a running shoe is not a hike-camp sock), and the price target must land the ATV with
     * those weights in force. Three alternating rounds, each department-first; fixed seed, so deterministic.
     * Weights are the store's BASE acceptance weights (see [StoryCalendar.departmentSalesTargets] for the
     * mix they aim at); the day's seasonal factors multiply them in [run].
     */
    private val calibration: Pair<Double, Map<String, Double>> = run {
        val want = baseModel.basket.atvUsd.value / baseModel.basket.unitsPerTxn.value
        val shareTargets = StoryCalendar.departmentSalesTargets(catalog.all.groupingBy { it.department }.eachCount())
        var target = baseModel.basket.avgLinePriceUsd.value
        var weights: Map<String, Double> = emptyMap()
        repeat(CALIBRATION_ROUNDS) {
            weights = catalog.calibrateDepartmentWeights(shareTargets, samplerModel(target), CALIBRATION_SEED)
            repeat(CALIBRATION_PASSES) { target *= want / meanLinePrice(target, weights) }
        }
        target to weights
    }

    /**
     * The seasonal department factors move the sold mix through the year (more cycling in spring, less snow
     * in July), and with it the ATV. This holds it level: the line price target at each mid-month is the
     * calibrated one rescaled by how much that month's weights move the mean line price (same random stream
     * both sides, so the ratio is steady), interpolated by day between mid-months.
     */
    private val monthlyPriceTarget: DoubleArray = run {
        val target = calibration.first
        val base = meanLinePrice(target, calibration.second, MONTHLY_BASKETS)
        DoubleArray(12) { m ->
            val w = calibration.second.mapValues { (d, v) -> v * (seasonalWeights(LocalDate.of(MONTHLY_YEAR, m + 1, 15))[d] ?: 1.0) }
            target * base / meanLinePrice(target, w, MONTHLY_BASKETS)
        }
    }

    /** The line price target on [date]: the store's calibrated one, corrected for the season's department mix. */
    fun samplerLinePriceTarget(date: LocalDate): Double {
        val mid = LocalDate.of(date.year, date.monthValue, 15)
        val (a, b) = if (date.isBefore(mid)) mid.minusMonths(1) to mid else mid to mid.plusMonths(1)
        val t = java.time.temporal.ChronoUnit.DAYS.between(a, date).toDouble() / java.time.temporal.ChronoUnit.DAYS.between(a, b)
        val pa = monthlyPriceTarget[a.monthValue - 1]
        val pb = monthlyPriceTarget[b.monthValue - 1]
        return pa + (pb - pa) * t
    }

    /** The calibrated base line price target (mid-year season-neutral weights). */
    val samplerLinePriceTarget: Double get() = calibration.first

    /** The store's base department acceptance weights (heaviest = 1.0), before the day's seasonal factors. */
    val departmentBase: Map<String, Double> get() = calibration.second

    private fun samplerModel(linePriceTarget: Double): OperatingModel =
        baseModel.copy(basket = baseModel.basket.copy(unitsPerTxn = Tagged(samplerUnitTarget), avgLinePriceUsd = Tagged(linePriceTarget)))

    private fun meanLinePrice(target: Double, weights: Map<String, Double>, baskets: Int = CALIBRATION_BASKETS): Double {
        val m = samplerModel(target)
        val rng = kotlin.random.Random(CALIBRATION_SEED)
        val weighted = catalog.withDepartmentWeights(weights)
        var units = 0L
        var value = 0.0
        repeat(baskets) {
            weighted.sampleBasket(rng, m).forEach {
                units++
                value += it.priceUsd
            }
        }
        return value / units
    }

    /** Region codes that hold at least one fixture — the regions department traffic can be measured in. */
    fun fixtureRegionCodes(): Set<String> = fixtureRegion.values.toSet()

    val allSkus: List<StoreCatalog.Sku> get() = catalog.all

    data class DayPlan(
        val date: LocalDate,
        val seed: Long,
        val dayType: TrafficGenerator.DayType,
        val seasonality: Double,
        /** everything else that scales footfall: area × holiday × promo × store story × weather noise */
        val populationScale: Double,
        /** target P(a session is a buying session) for the day */
        val buyerShare: Double,
        /** P(a session is the Shoplift arc) — set so the chain sees ~3 gate alarms per store-week */
        val shopliftShare: Double,
        val departmentWeights: Map<String, Double>,
    )

    class Hour {
        var visits = 0
        var transits = 0
        var sessionMsSum = 0L
        var sessions = 0
        var transactions = 0
        var units = 0
        var cents = 0L
    }

    class Dept {
        var units = 0
        var cents = 0L
        var transactions = 0
        val shoppers = HashSet<String>()
        var dwellMs = 0L
    }

    class Fix {
        val shoppers = HashSet<String>()
        var dwellMs = 0L
        var engagement = 0
    }

    data class Alarm(val at: Instant, val ean: String, val priceUsd: Double, val fixture: String)

    data class Sold(val fixture: String, val ean: String)

    /**
     * One till transaction, stamped when the shopper LEAVES — the journey publishes `SaleCompleted` at its
     * arrival instant (journeys run whole at arrival), and `CustomerExited` fires at the end of the checkout
     * dwell, which is when the receipt is printed. Used by the dated sale stream (2026-10-12); the history files
     * never read it, so adding it changes no byte of their output.
     */
    data class Txn(val at: Instant, val customerId: String, val lines: List<SaleLine>)

    class DayResult(
        val date: LocalDate,
        val openUtc: Instant,
        val hours: List<Hour>,
        /** keyed by region zone CODE */
        val departments: Map<String, Dept>,
        val fixtures: Map<String, Fix>,
        val alarms: List<Alarm>,
        val sold: List<Sold>,
        val schedulerErrors: Int,
        /** every till transaction with its exit-time stamp, in the order they closed */
        val txns: List<Txn> = emptyList(),
    ) {
        val visits: Int get() = hours.sumOf { it.visits }
        val transactions: Int get() = hours.sumOf { it.transactions }
        val units: Int get() = hours.sumOf { it.units }
        val cents: Long get() = hours.sumOf { it.cents }
    }

    /** Buffers one shopper at a time; runs the oracle on eviction. */
    private inner class OracleSink(val onShopper: (String, List<ImpressionOracle.Predicted>) -> Unit) : AtomSink {
        private val buffers = HashMap<String, ArrayList<ImpressionOracle.Sample>>()
        val lastTs = HashMap<String, Long>()

        override fun emitSamples(objectId: String, samples: List<ImpressionOracle.Sample>) {
            if (samples.isEmpty()) return
            buffers.getOrPut(objectId) { ArrayList() }.addAll(samples)
            lastTs[objectId] = samples.last().tsMs
        }

        override fun evict(objectId: String) {
            val s = buffers.remove(objectId) ?: emptyList<ImpressionOracle.Sample>()
            onShopper(objectId, if (s.isEmpty()) emptyList() else oracle.run(fixtures, s.sortedBy { it.tsMs }))
        }
    }

    fun run(plan: DayPlan): DayResult {
        val model = adjustedModel(plan)
        // the store's base mix × the day's seasonal factor, per department the store carries
        val dayWeights = departmentBase.mapValues { (d, w) -> w * (plan.departmentWeights[d] ?: 1.0) }
        val journeys = Journeys(fixtures, zones, catalog.withDepartmentWeights(dayWeights), model).withGates(gates)

        val openTime = LocalTime.parse(model.store.operatingHours.open)
        val openUtc = ZonedDateTime.of(plan.date, openTime, store.zone).toInstant()
        val openHours = model.store.operatingHours.openHours
        val clock = SimpleClock(openUtc)
        val scheduler = QueueScheduler(clock, FailurePolicy.SKIP_AND_LOG)
        val bus = SimpleEventBus()

        val hours = List(openHours) { Hour() }
        val departments = HashMap<String, Dept>()
        val fixtureAgg = HashMap<String, Fix>()
        val alarms = ArrayList<Alarm>()
        val sold = ArrayList<Sold>()
        val txns = ArrayList<Txn>()
        val pendingSale = HashMap<String, SaleCompleted>()
        val entryMs = HashMap<String, Long>()
        val concealed = HashMap<String, ItemConcealed>()
        val departmentCode: Map<String, String> = store.departments.associate { it.department!! to it.code }

        fun hourOf(customer: String): Hour {
            val ms = entryMs[customer] ?: openUtc.toEpochMilli()
            return hours[((ms - openUtc.toEpochMilli()) / 3_600_000L).toInt().coerceIn(0, openHours - 1)]
        }

        val sink = OracleSink { customer, predicted ->
            for (p in predicted) {
                fixtureAgg.getOrPut(p.fixtureCode) { Fix() }.apply {
                    shoppers += customer
                    dwellMs += p.durationMs
                }
                fixtureRegion[p.fixtureCode]?.let { region ->
                    departments.getOrPut(region) { Dept() }.apply {
                        shoppers += customer
                        dwellMs += p.durationMs
                    }
                }
            }
        }

        bus.subscribe(CustomerEntered::class) {
            entryMs[it.customerId] = it.at.toEpochMilli()
            hourOf(it.customerId).visits++
        }
        bus.subscribe(CustomerExited::class) {
            pendingSale.remove(it.customerId)?.let { s -> txns += Txn(it.at, s.customerId, s.lines) }
            val start = entryMs[it.customerId] ?: return@subscribe
            val ms = it.at.toEpochMilli() - start
            hourOf(it.customerId).apply {
                sessionMsSum += ms
                sessions++
                if (ms < TRANSIT_MAX_MS) transits++
            }
        }
        bus.subscribe(SaleCompleted::class) { s ->
            pendingSale[s.customerId] = s
            val h = hourOf(s.customerId)
            h.transactions++
            h.units += s.units
            var primary: Pair<String, Long>? = null
            for (line in s.lines) {
                val c = Math.round(line.priceUsd * 100.0)
                h.cents += c
                val region = departmentCode[line.department]
                if (region != null) {
                    departments.getOrPut(region) { Dept() }.apply {
                        units++
                        cents += c
                    }
                    if (primary == null || c > primary.second) primary = region to c
                }
                fixtureAgg.getOrPut(line.fixture) { Fix() }.engagement++
                sold += Sold(line.fixture, line.ean)
            }
            primary?.let { departments.getValue(it.first).transactions++ }
        }
        bus.subscribe(ItemConcealed::class) {
            concealed[it.customerId] = it
            fixtureAgg.getOrPut(it.fixture) { Fix() }.engagement++
        }
        bus.subscribe(EasGateCrossed::class) { g ->
            if (!g.shouldAlarm) return@subscribe
            val item = concealed[g.customerId] ?: return@subscribe
            // The crossing time is the end of the walk-out the journey just emitted — not the arrival
            // instant the bus stamps (journeys run whole at arrival; their samples carry the real times).
            val at = sink.lastTs[g.customerId]?.let { Instant.ofEpochMilli(it) } ?: g.at
            alarms += Alarm(at, item.ean, item.priceUsd, item.fixture)
        }

        val generator = TrafficGenerator(
            model,
            journeys,
            TrafficGenerator.Params(
                date = plan.date,
                zone = store.zone,
                dayTypeOverride = plan.dayType,
                seasonalityFactor = plan.seasonality,
                populationScale = plan.populationScale,
            ),
        )
        val ctx = GeneratorContext(clock, scheduler, bus, forkRng(plan.seed, generator.id), log, sink)
        generator.start(ctx)
        scheduler.drain()
        generator.stop(ctx)

        // Fixtures with nothing at all still get a zero row (a measured zero for a fixture the pipeline sees).
        // a sale whose exit never fired (none expected) keeps its arrival stamp rather than vanishing
        pendingSale.values.sortedBy { it.at }.forEach { txns += Txn(it.at, it.customerId, it.lines) }
        return DayResult(plan.date, openUtc, hours, departments, fixtureAgg, alarms, sold, scheduler.errorCount, txns)
    }

    /**
     * The operating model with the day's conversion and shoplift share — via the persona mix, the only place
     * the generator reads them. Browse weight is held; the buying weights scale together so the
     * shop-and-buy : try-on split is the model's own.
     */
    private fun adjustedModel(plan: DayPlan): OperatingModel {
        val pm = baseModel.personaMix
        val buyers = pm.shopAndBuy + pm.tryOnAndPartialBuy
        val p = plan.buyerShare.coerceIn(0.01, 0.9)
        // solve k·buyers / (browse + k·buyers + s) = p
        val k = p * (pm.browseAndLeave + plan.shopliftShare) / ((1 - p) * buyers)
        return baseModel.copy(
            conversion = baseModel.conversion.copy(overallRate = Tagged(p)),
            basket = baseModel.basket.copy(unitsPerTxn = Tagged(samplerUnitTarget), avgLinePriceUsd = Tagged(samplerLinePriceTarget(plan.date))),
            personaMix = pm.copy(
                shopAndBuy = pm.shopAndBuy * k,
                tryOnAndPartialBuy = pm.tryOnAndPartialBuy * k,
                shopliftBaseline = plan.shopliftShare,
            ),
        )
    }

    companion object {
        /** A session shorter than this counts as a transit (walk-through) in `traffic_store_hourly`. */
        const val TRANSIT_MAX_MS = 5 * 60_000L

        private const val CALIBRATION_PASSES = 3
        private const val CALIBRATION_ROUNDS = 3
        private const val MONTHLY_BASKETS = 8_000
        private const val MONTHLY_YEAR = 2026
        private const val CALIBRATION_BASKETS = 20_000
        private const val CALIBRATION_SEED = 20261016L

        /**
         * The unit target t whose sampled mean `E[max(1, round(t + U(-0.8, 0.8)))]` equals [want] — exact,
         * by bisection on the closed form (the integer boundaries of a uniform window).
         */
        fun solveUnitTarget(want: Double): Double {
            fun mean(t: Double): Double {
                val lo = t - 0.8
                val hi = t + 0.8
                var e = 0.0
                var k = 0
                while (k - 0.5 < hi) {
                    val a = maxOf(lo, k - 0.5)
                    val b = minOf(hi, k + 0.5)
                    if (b > a) e += maxOf(1, k) * (b - a) / 1.6
                    k++
                }
                return e
            }
            var a = want - 1.0
            var b = want + 1.0
            repeat(60) {
                val m = (a + b) / 2
                if (mean(m) < want) a = m else b = m
            }
            return (a + b) / 2
        }

        /** Buying share the unmodified model implies (persona mix, renormalised with the shoplift baseline). */
        fun modelBuyerShare(model: OperatingModel): Double {
            val pm = model.personaMix
            return (pm.shopAndBuy + pm.tryOnAndPartialBuy) / (pm.browseAndLeave + pm.shopAndBuy + pm.tryOnAndPartialBuy + pm.shopliftBaseline)
        }
    }
}
