/**
 * The DATED mode of `connectSaleStream` / `connectChainActivity` (BRIEF-TWIN-RECENT-WINDOW § 1.2) — on when
 * `M8TRX_STREAM_DATE` is set; without it both drivers behave exactly as before.
 *
 * A dated run streams ONE calendar day per store, generated by [RecentDay] (the history generator's own
 * store-day: operating model × story × seed), so the live days continue the year the dashboards already hold:
 *
 *  - **Volume** is the model's, per store, per day (Denver ≈ 250–290 transactions on an October weekday).
 *  - **`occurred_at`** is the transaction's own time — the shopper's exit from the store — so sales spread
 *    across the store's operating hours instead of landing as a burst at send time.
 *  - **One sale event per transaction**: `epc` for a one-unit basket, `epc_list` for the rest.
 *  - **Each EPC sells once, from what the store HOLDS.** Every basket line takes a unit of its own EAN from the store's
 *    on-hand list ([onHand]): the seed `epcs.csv` ∪ the units the twin received there (`receive/received-stock.csv`: the
 *    chain receipt and the Denver reset's), each at its CURRENT fixture (`moves/placements.csv`, the twin's location ledger,
 *    a later line wins) else the fixture it was seeded/received to. Back-of-house (`BR-*`, by that current fixture) first so
 *    the floor still looks stocked; never a unit in the shared sold-log, in `stock/missing-epcs.txt` (a count's
 *    `missing`), or reserved by another date's plan. A received unit's item code comes from the store's `assortment.csv`
 *    by EAN, so the restock manifest counts it. A line whose EAN has no unit left is dropped and counted. The run
 *    prints each store's runway (units left ÷ today's units) — the brief's budget is ≥ 12 days.
 *  - **Resumable.** A live run persists its plan (`.twin-state/stream/<runId>.plan.csv`) and a sent ledger
 *    (`<runId>.sent`). A re-run of the same date and seed reuses the plan, skips what was sent, and sends
 *    what has come due — so a day can be streamed in two passes (Korea at 22:00 KST, the US stores the next
 *    afternoon) without a unit being sold twice or an id being re-used.
 *  - **Nothing in the future** is sent unless `M8TRX_STREAM_ALLOW_FUTURE=true`: the read windows are
 *    `[now-24h, now)`, so a future-dated sale reads as missing until the clock catches up.
 *  - **Chain mode only:** per store-day one restock manifest (what sold, rounded up to cases of 6) shortly
 *    after open, `M8TRX_DAY_PRICINGS` (2) price changes and `M8TRX_DAY_CATALOGS` (1) catalog re-asserts.
 *    ⚠ Those three payloads carry no event time in the §8 contract, so they land at SEND time.
 *
 * DRY-RUN unless `M8TRX_STREAM_LIVE=true` — the dated mode is new, so it is opt-in even though the undated
 * drivers fire on run. A dry run writes no state.
 *
 * Env: `M8TRX_STREAM_DATE` (yyyy-mm-dd) · `M8TRX_STREAM_SEED` (20261016, the history's) · `M8TRX_STREAM_STORES`
 * (csv; SaleStream default dec-us-denver, ChainActivity default all) · `M8TRX_STREAM_LIVE` (false) ·
 * `M8TRX_STREAM_ALLOW_FUTURE` (false) · `M8TRX_STREAM_GAP_MS` (120 → ≤ 8/s, under the measured ≤ 12 ceiling) ·
 * `M8TRX_STREAM_MAX_ERRORS` (5 consecutive refusals stop the run) · `M8TRX_STREAM_LIMIT` (send at most N
 * events — the warm-up) · `M8TRX_STREAM_SOLD_LOG` · `M8TRX_RUN_ID` (default `twin-day-<yyyymmdd>-<seed>`) ·
 * `M8TRX_CHAIN_DIR` · the on-hand sources, each defaulting beside the sold-log's directory `<state>`:
 * `M8TRX_STREAM_RECEIVED` (`<state>/receive/received-stock.csv`; a missing file = seed only) ·
 * `M8TRX_STREAM_PLACEMENTS` (`<state>/moves/placements.csv`) · `M8TRX_STREAM_MISSING` (`<state>/stock/missing-epcs.txt`) ·
 * `M8TRX_STREAM_REUSE_PLAN` (false; a DRY run reads the persisted plan too, to report what the floor guard would swap).
 *
 * **Floor only (server lane, 2026-11-21).** A sale takes a unit on a sales-floor fixture; `BR-*` stock never sells until a
 * move has put it on the floor. [allocate] excludes it; a FROZEN plan that still holds a back-room unit is repaired at send
 * time by [guardFloor]: the unit is swapped for a floor unit of the same EAN (or dropped), persisted in `<runId>.swaps.csv`.
 */
object DatedStream {
    private val log = LoggerFactory.getLogger("com.m8trx.twin.connect.DatedStream")

    data class EpcRow(val epc: String, val ean: String, val fixture: String, val itemCd: String = "") {
        val backOfHouse: Boolean get() = fixture.startsWith("BR-")
    }

    data class PlannedSale(val saleId: String, val store: String, val at: Instant, val epcs: List<String>)

    data class StorePlan(
        val store: String,
        val date: LocalDate,
        val closed: Boolean,
        val sales: List<PlannedSale>,
        val units: Int,
        val droppedLines: Int,
        val substitutedLines: Int,
        val unitsLeft: Int,
        val visits: Int,
        val revenueUsd: Double,
        val open: Instant?,
        val close: Instant?,
    ) {
        val runwayDays: Double get() = if (units == 0) Double.POSITIVE_INFINITY else unitsLeft.toDouble() / units
    }

    /** `epcs.csv` (epc,ean,item_cd,category,fixture,store_id) → rows, header dropped, blanks skipped. */
    fun loadEpcRows(file: Path): List<EpcRow> = Files.readAllLines(file).drop(1).mapNotNull { line ->
        val c = line.split(",")
        if (c.size < 6 || c[0].isBlank()) null else EpcRow(c[0].trim(), c[1].trim(), c[4].trim(), c[2].trim())
    }

    /** The twin's own stock ledgers a dated run reads (all read-only; a missing file is an empty ledger). */
    data class StockSources(val received: Path, val placements: Path, val missing: Path) {
        companion object {
            fun fromEnv(soldLog: Path): StockSources {
                val state = soldLog.parent ?: Path.of(".twin-state")
                fun env(k: String, d: Path) = System.getenv(k)?.takeIf { it.isNotBlank() }?.let { Path.of(it) } ?: d
                return StockSources(
                    env("M8TRX_STREAM_RECEIVED", state.resolve("receive/received-stock.csv")),
                    env("M8TRX_STREAM_PLACEMENTS", state.resolve("moves/placements.csv")),
                    env("M8TRX_STREAM_MISSING", state.resolve("stock/missing-epcs.txt")),
                )
            }
        }
    }

    /**
     * Pure merge: [seed] rows then the [received] rows of [slug], de-duplicated by EPC (the seed row wins), every unit at its
     * CURRENT fixture ([placements]: epc → fixture, else the fixture it was seeded/received to). A received unit's item code
     * is its EAN's in [itemCdByEan] (the seed rows' item codes fill any EAN the assortment lacks).
     */
    fun mergeOnHand(
        slug: String,
        seed: List<EpcRow>,
        received: List<ReceiveStock.ReceivedRow>,
        placements: Map<String, String>,
        itemCdByEan: Map<String, String>,
    ): List<EpcRow> {
        val cd = seed.filter { it.itemCd.isNotBlank() }.associate { it.ean to it.itemCd } + itemCdByEan
        val rec = received.asSequence().filter { it.slug == slug }.map { EpcRow(it.epc, it.ean, it.fixture, cd[it.ean].orEmpty()) }
        return (seed.asSequence() + rec).distinctBy { it.epc }
            .map { r -> placements[r.epc]?.takeIf { it != r.fixture }?.let { r.copy(fixture = it) } ?: r }.toList()
    }

    /** What [slug] holds, before the sold-log, the missing list and other dates' reservations come off: seed ∪ received at their current fixtures. */
    fun onHand(chainDir: Path, slug: String, src: StockSources): List<EpcRow> =
        onHand(chainDir, slug, ReceiveStock.readStock(src.received).filter { it.slug == slug }, RestockMoves.readPlacements(src.placements))

    /** [onHand] from ledgers the caller already read once ([received] = this store's rows, [placements] = the whole ledger). */
    fun onHand(chainDir: Path, slug: String, received: List<ReceiveStock.ReceivedRow>, placements: Map<String, String>): List<EpcRow> {
        val dir = chainDir.resolve("stores/$slug")
        return mergeOnHand(
            slug,
            loadEpcRows(dir.resolve("epcs.csv")),
            received,
            placements,
            loadItemCdByEan(dir.resolve("assortment.csv")),
        )
    }

    /** `assortment.csv` → EAN → item_cd (empty when the file is absent). */
    internal fun loadItemCdByEan(file: Path): Map<String, String> {
        if (!Files.exists(file)) return emptyMap()
        val lines = Files.readAllLines(file)
        if (lines.size < 2) return emptyMap()
        val h = csvSplit(lines.first())
        val iEan = h.indexOf("ean")
        val iItem = h.indexOf("item_cd")
        if (iEan < 0 || iItem < 0) return emptyMap()
        return lines.drop(1).mapNotNull { l ->
            val c = csvSplit(l)
            val e = c.getOrNull(iEan)?.trim().orEmpty()
            val i = c.getOrNull(iItem)?.trim().orEmpty()
            if (e.isEmpty() || i.isEmpty()) null else e to i
        }.toMap()
    }

    /** `assortment.csv` → EAN → (department, price_usd): what a substitute is matched on. */
    fun loadCatalog(file: Path): Map<String, Pair<String, Double>> {
        val lines = Files.readAllLines(file)
        val h = lines.first().split(",")
        val iEan = h.indexOf("ean")
        val iDept = h.indexOf("department")
        val iPrice = h.indexOf("price_usd")
        require(iEan >= 0 && iDept >= 0 && iPrice >= 0) { "$file lacks ean/department/price_usd" }
        return lines.drop(1).mapNotNull { l ->
            val c = csvSplit(l)
            val price = c.getOrNull(iPrice)?.toDoubleOrNull() ?: return@mapNotNull null
            c[iEan].trim() to (c[iDept].trim() to price)
        }.toMap()
    }

    /**
     * Allocate the day's baskets to real units. Pure and deterministic: queues per EAN of SALES-FLOOR units only, in EPC
     * order; a back-of-house unit (`BR-*` by its current fixture) is never for sale until a move has put it on the floor,
     * and [exclude] (sold or reserved) never sells.
     *
     * The basket sampler concentrates on SKUs near the target line price, and a store holds 1–10 units of
     * each, so a busy day exhausts its favorites by mid-afternoon — 45 % of Denver's lines on 2026-10-10. A
     * line whose own EAN is out therefore takes the nearest-priced EAN **of the same department** that still
     * has a unit (a shopper buying the next tent over), keeping units per transaction and the department mix
     * intact; it is dropped only if the department is out. Substitutions are counted.
     */
    fun allocate(
        day: RecentDay.Day,
        rows: List<EpcRow>,
        exclude: Set<String>,
        runId: String,
        catalog: Map<String, Pair<String, Double>> = emptyMap(),
    ): StorePlan {
        val queues = rows.asSequence().filter { it.epc !in exclude }.distinctBy { it.epc }
            .filter { !it.backOfHouse }
            .sortedBy { it.epc }
            .groupBy { it.ean }
            .mapValues { (_, rs) -> ArrayDeque(rs) }
        // department → EANs with stock, price-sorted (ties by EAN) — the substitute pool
        val pool: Map<String, MutableList<Pair<Double, String>>> = queues.keys.mapNotNull { e -> catalog[e]?.let { (d, p) -> Triple(d, p, e) } }
            .groupBy({ it.first }, { it.second to it.third })
            .mapValues { (_, l) -> l.sortedWith(compareBy({ it.first }, { it.second })).toMutableList() }
        fun take(ean: String): EpcRow? {
            val q = queues[ean] ?: return null
            val r = q.removeFirstOrNull()
            if (q.isEmpty()) catalog[ean]?.let { (d, p) -> pool[d]?.remove(p to ean) }
            return r
        }
        var dropped = 0
        var substituted = 0
        var units = 0
        val sales = ArrayList<PlannedSale>(day.txns.size)
        day.txns.forEachIndexed { i, t ->
            val epcs = t.lines.mapNotNull { line ->
                var r = take(line.ean)
                if (r == null) {
                    val sub = pool[line.department]?.minByOrNull { (p, _) -> kotlin.math.abs(p - line.priceUsd) }
                    if (sub != null) {
                        r = take(sub.second)
                        if (r != null) substituted++
                    }
                }
                if (r == null) dropped++
                r?.epc
            }
            if (epcs.isNotEmpty()) {
                units += epcs.size
                sales += PlannedSale("$runId-${day.slug}-${"%04d".format(i + 1)}", day.slug, t.at, epcs)
            }
        }
        return StorePlan(
            store = day.slug,
            date = day.date,
            closed = false,
            sales = sales,
            units = units,
            droppedLines = dropped,
            substitutedLines = substituted,
            unitsLeft = queues.values.sumOf { it.size },
            visits = day.visits,
            revenueUsd = day.cents / 100.0,
            open = day.open,
            close = day.close,
        )
    }

    /** The wire shape of one planned sale — `epc` for a single unit, `epc_list` otherwise; `occurred_at` is the transaction's time. */
    fun toSaleEvent(s: PlannedSale): SaleEvent = toSaleEvent(s.saleId, s.at, s.epcs)

    private fun toSaleEvent(saleId: String, at: Instant, epcs: List<String>): SaleEvent = if (epcs.size == 1) {
        SaleEvent.byEpc(saleId, at.toString(), epcs.single())
    } else {
        SaleEvent.byEpcList(saleId, at.toString(), epcs)
    }

    /**
     * One event's worth of a receipt: the units of [sale] that sold at one price (CORE-REQ-007). [id] is the ledger id —
     * the sale's own id when the receipt has one price, `<saleId>#<n>` per price otherwise; the wire id is always the
     * receipt's ([PlannedSale.saleId]), so the platform numbers the lines across the parts. [priceMinor] is in the ISO
     * 4217 minor unit of [currency], the **store's own** (KRW whole won in Seoul, EUR cents in Paris, USD cents in Denver:
     * the platform keeps it on `sale_line`, `till`). Null = a unit the twin has no price for (its EAN is not in the store's
     * assortment): sent unpriced, the platform values it.
     */
    internal data class PricedPart(
        val sale: PlannedSale,
        val id: String,
        val epcs: List<String>,
        val priceMinor: Long?,
        val currency: String?,
        val source: PriceBook.Source?,
    )

    /** The wire shape of one part: the receipt's id and time, the part's units, one unit's price + `currency`, the store's. */
    internal fun toSaleEvent(part: PricedPart): SaleEvent =
        toSaleEvent(part.sale.saleId, part.sale.at, part.epcs).let { e -> part.currency?.let { e.priced(part.priceMinor, it) } ?: e }

    /**
     * Price every unit of [s] at its moment from [book], at the sale's own store (the last change remembered there, else
     * the store's list price, in its currency) and split the receipt into one part per price, in first-appearance order.
     * Pure: the same plan, memory and book give the same parts.
     */
    internal fun priceSale(s: PlannedSale, eanByEpc: Map<String, String>, book: PriceBook): List<PricedPart> {
        val priced = s.epcs.map { epc -> epc to eanByEpc[epc]?.let { book.at(s.store, it, s.at) } }
        val groups = LinkedHashMap<Pair<Long, String>?, MutableList<Pair<String, PriceBook.Price?>>>()
        priced.forEach { (epc, p) -> groups.getOrPut(p?.let { it.minor to it.currency }) { ArrayList() } += epc to p }
        return groups.entries.mapIndexed { i, (price, units) ->
            PricedPart(
                sale = s,
                id = if (groups.size == 1) s.saleId else "${s.saleId}#${i + 1}",
                epcs = units.map { it.first },
                priceMinor = price?.first,
                currency = price?.second,
                // A part mixes sources only when an update and the list agree to the cent; name the update then.
                source = units.mapNotNull { it.second?.source }.minByOrNull { it.ordinal },
            )
        }
    }

    data class Swap(val orig: String, val new: String, val saleId: String)

    const val DROPPED = "DROPPED"

    internal data class Guarded(val sales: List<PlannedSale>, val fresh: List<Swap>)

    /** `<runId>.swaps.csv` (orig_epc,new_epc|DROPPED,sale_id) → orig → new; a missing file is no swaps. */
    internal fun readSwaps(file: Path): List<Swap> = if (!Files.exists(file)) {
        emptyList()
    } else {
        Files.readAllLines(file).drop(1).filter { it.isNotBlank() }.map { l -> l.split(",").let { Swap(it[0], it[1], it[2]) } }
    }

    internal fun appendSwaps(file: Path, swaps: List<Swap>) {
        if (swaps.isEmpty()) return
        if (!Files.exists(file)) Files.write(file, listOf("orig_epc,new_epc,sale_id"))
        Files.write(file, swaps.map { "${it.orig},${it.new},${it.saleId}" }, StandardOpenOption.APPEND)
    }

    /** Apply recorded swaps: the new unit takes the old one's place, DROPPED removes it; a sale left empty goes. */
    internal fun applySwaps(sales: List<PlannedSale>, swaps: Map<String, String>): List<PlannedSale> = sales.mapNotNull { s ->
        val e = s.epcs.mapNotNull { epc -> swaps[epc]?.let { n -> n.takeIf { it != DROPPED } } ?: epc.takeIf { it !in swaps } }
        if (e.isEmpty()) null else s.copy(epcs = e)
    }

    /**
     * The send-time floor guard for a FROZEN plan. First applies [existing] swaps, then for every sale for which [isDue]
     * holds, any unit whose CURRENT fixture in [stock] is back-of-house (and that is not already [sold]) is swapped for a
     * floor unit of the same EAN at the same store that is not sold, not [reservedElsewhere], not in this plan (before or
     * after swaps) and not already used; none left = DROPPED. Pure and deterministic (candidates in EPC order).
     */
    internal fun guardFloor(
        frozen: List<PlannedSale>,
        existing: List<Swap>,
        stock: Map<String, List<EpcRow>>,
        sold: Set<String>,
        reservedElsewhere: Set<String>,
        isDue: (PlannedSale) -> Boolean,
    ): Guarded {
        val applied = applySwaps(frozen, existing.associate { it.orig to it.new })
        val used = HashSet<String>().apply {
            frozen.forEach { addAll(it.epcs) }
            existing.forEach { if (it.new != DROPPED) add(it.new) }
        }
        val rowByEpc = stock.values.flatten().associateBy { it.epc }
        val queues = HashMap<Pair<String, String>, ArrayDeque<String>>()
        fun next(store: String, ean: String): String? = queues.getOrPut(store to ean) {
            ArrayDeque(
                stock[store].orEmpty().asSequence().filter { it.ean == ean && !it.backOfHouse }.map { it.epc }
                    .filter { it !in sold && it !in reservedElsewhere && it !in used }.sorted().toList(),
            )
        }.removeFirstOrNull()?.also { used += it }
        val fresh = ArrayList<Swap>()
        val out = applied.mapNotNull { s ->
            if (!isDue(s)) return@mapNotNull s
            val e = s.epcs.mapNotNull { epc ->
                val r = rowByEpc[epc]
                if (r == null || !r.backOfHouse || epc in sold) {
                    epc
                } else {
                    val n = next(s.store, r.ean)
                    fresh += Swap(epc, n ?: DROPPED, s.saleId)
                    n
                }
            }
            if (e.isEmpty()) null else s.copy(epcs = e)
        }
        return Guarded(out, fresh)
    }

    /** [parts] without the units already sold (the sold-log); a part left with no unit is dropped. */
    internal fun unsoldParts(parts: List<PricedPart>, sold: Set<String>): List<PricedPart> =
        parts.mapNotNull { p -> p.epcs.filter { it !in sold }.takeIf { it.isNotEmpty() }?.let { p.copy(epcs = it) } }

    /**
     * Whether a ledger already holds [id], or the whole receipt under its own id: receipts sent before the split (one
     * event, id = sale id) must never be re-sent as parts, since their units are sold and the platform would refuse them.
     */
    internal fun alreadySent(id: String, saleId: String?, sent: Set<String>): Boolean = id in sent || (saleId != null && saleId in sent)

