    fun run(defaultStores: List<String>, chainOps: Boolean) {
        val date = LocalDate.parse(System.getenv("M8TRX_STREAM_DATE"))
        val seed = System.getenv("M8TRX_STREAM_SEED")?.toLongOrNull() ?: RecentDay.HISTORY_SEED
        val live = System.getenv("M8TRX_STREAM_LIVE")?.toBooleanStrictOrNull() ?: false
        val allowFuture = System.getenv("M8TRX_STREAM_ALLOW_FUTURE")?.toBooleanStrictOrNull() ?: false
        val gapMs = System.getenv("M8TRX_STREAM_GAP_MS")?.toLongOrNull() ?: 120L
        val maxErrors = System.getenv("M8TRX_STREAM_MAX_ERRORS")?.toIntOrNull() ?: 5
        val limit = System.getenv("M8TRX_STREAM_LIMIT")?.toIntOrNull()
        val chainDir = Path.of(System.getenv("M8TRX_CHAIN_DIR")?.takeIf { it.isNotBlank() } ?: "reference/data/chain")
        val runId = System.getenv("M8TRX_RUN_ID")?.takeIf { it.isNotBlank() } ?: "twin-day-${date.format(DateTimeFormatter.BASIC_ISO_DATE)}-$seed"
        val soldLog = Path.of(System.getenv("M8TRX_STREAM_SOLD_LOG")?.takeIf { it.isNotBlank() } ?: ".twin-state/sold-epcs.txt")
        val stateDir = soldLog.parent?.resolve("stream") ?: Path.of(".twin-state/stream")
        val planFile = stateDir.resolve("$runId.plan.csv")
        val sentFile = stateDir.resolve("$runId.sent")
        val stores = System.getenv("M8TRX_STREAM_STORES")?.split(",")?.map { it.trim() }?.filter { it.isNotEmpty() } ?: defaultStores
        val t0 = System.currentTimeMillis()

        log.info(
            "═══ dated stream ═══ date={} seed={} stores={} chainOps={} live={} runId={}",
            date,
            seed,
            stores.size,
            chainOps,
            live,
            runId,
        )

        val recent = RecentDay(seed, chainDir)
        val priorSold = readPriorSold(soldLog)
        val reservedElsewhere = reservedByOtherPlans(stateDir, planFile)
        val sources = StockSources.fromEnv(soldLog)
        val missing = StoreStock.readLines(sources.missing)
        val receivedBySlug = ReceiveStock.readStock(sources.received).groupBy { it.slug }
        val placements = RestockMoves.readPlacements(sources.placements)
        val stock: Map<String, List<EpcRow>> = stores.associateWith { onHand(chainDir, it, receivedBySlug[it].orEmpty(), placements) }
        log.info(
            "on hand (seed ∪ received, current fixtures): {} · sources received={} placements={} missing={} ({} units)",
            stock.mapValues { it.value.size },
            sources.received,
            sources.placements,
            sources.missing,
            missing.size,
        )
        val reusePlanDry = System.getenv("M8TRX_STREAM_REUSE_PLAN")?.toBooleanStrictOrNull() ?: false
        val reused = (live || reusePlanDry) && Files.exists(planFile)
        val swapsFile = stateDir.resolve("$runId.swaps.csv")
        val plans: List<StorePlan> = stores.map { slug ->
            val day = recent.run(slug, date)
            if (day == null) {
                StorePlan(slug, date, true, emptyList(), 0, 0, 0, 0, 0, 0.0, null, null)
            } else {
                allocate(
                    day,
                    stock.getValue(slug),
                    priorSold + reservedElsewhere + missing,
                    runId,
                    loadCatalog(chainDir.resolve("stores/$slug/assortment.csv")),
                )
            }
        }
        val allocated: List<PlannedSale> = if (reused) readPlan(planFile).filter { it.store in stores } else plans.flatMap { it.sales }
        val now = Instant.now()
        val existingSwaps = readSwaps(swapsFile)
        // The floor guard: a frozen plan may still hold back-room units; a fresh allocation never does.
        val guarded = guardFloor(
            allocated,
            existingSwaps,
            stock,
            priorSold + missing,
            reservedElsewhere,
        ) { allowFuture || !it.at.isAfter(now) }
        val sales: List<PlannedSale> = guarded.sales
        val storeOf = allocated.associate { it.saleId to it.store }
        (
            existingSwaps.map {
                it to false
            } + guarded.fresh.map { it to true }
            ).groupBy { storeOf[it.first.saleId] ?: "?" }.toSortedMap().forEach { (st, l) ->
            log.info(
                "  FLOOR GUARD {}: back-room units swapped {} · dropped {} (this run: swapped {} · dropped {})",
                st,
                l.count { it.first.new != DROPPED },
                l.count { it.first.new == DROPPED },
                l.count { it.second && it.first.new != DROPPED },
                l.count { it.second && it.first.new == DROPPED },
            )
        }
        val emptied = allocated.count { a -> sales.none { it.saleId == a.saleId } }
        if (emptied > 0) log.info("  FLOOR GUARD: {} sale(s) left with no floor unit — skipped", emptied)
        if (reused) log.info("reusing the persisted plan {} ({} sales) — the allocation is frozen at first live run", planFile, sales.size)

        plans.forEach { p ->
            if (p.closed) {
                log.info("  {} CLOSED on {} (story holiday) — nothing to stream", p.store, p.date)
            } else {
                log.info(
                    "  {} txn={} units={} (floor only) substituted={} dropped={} visits={} revenue≈\${} hours {}..{} · units left {} → runway {} days",
                    p.store,
                    p.sales.size,
                    p.units,
                    p.substitutedLines,
                    p.droppedLines,
                    p.visits,
                    "%.0f".format(p.revenueUsd),
                    p.open,
                    p.close,
                    p.unitsLeft,
                    "%.1f".format(p.runwayDays),
                )
            }
        }
        val lowRunway = plans.filter { !it.closed && it.runwayDays < 12.0 }
        if (lowRunway.isNotEmpty()) {
            log.warn(
                "  ⚠ runway under 12 days at today's rate: {}",
                lowRunway.map {
                    "${it.store}=${"%.1f".format(it.runwayDays)}"
                },
            )
        }

        val ops: List<OpItem> = if (chainOps) plannedOps(plans, sales, chainDir, seed, runId, stock = stock) else emptyList()
        // CORE-REQ-007: every unit sells at the price its store last set for it, in the store's currency — the memory of
        // sent updates plus this run's planned ones, on the plan's clock — else at the store's list (price_local). One
        // event per price per receipt. The pricing_update itself is the catalog's base price in the tenant's currency (EUR for Decathlon, CORE-REQ-008).
        val memoryFile = PriceMemory.file(soldLog)
        val remembered = PriceMemory.read(memoryFile)
        val plannedPrices = ops.mapNotNull { op -> op.churn?.let { PriceMemory.entryOf(op.id, op.at, op.store, it) } }
        val book = PriceBook(
            PriceBook.listOf(stores.associateWith { loadAssortment(chainDir.resolve("stores/$it/assortment.csv")) }),
            remembered + plannedPrices,
        )
        val eanByEpc = stock.values.flatten().associate { it.epc to it.ean }
        // A unit already in the sold-log never goes on the wire again, whatever ids the split gives a receipt this run
        // (a book that changed between passes can re-split a partly sent receipt; the platform refuses a sold EPC).
        val parts = sales.flatMap { priceSale(it, eanByEpc, book) }.let { all -> unsoldParts(all, priorSold + missing) }
        logPriceCoverage(sales.size, parts, remembered.size, plannedPrices.size)
        val items: List<Item> = (parts.map { SaleItem(it) } + ops).sortedBy { it.at }
        val sent = if (Files.exists(sentFile)) Files.readAllLines(sentFile).map { it.trim() }.toSet() else emptySet()
        fun isSent(it: Item) = alreadySent(it.id, (it as? SaleItem)?.part?.sale?.saleId, sent)
        val due = items.filter { !isSent(it) && (allowFuture || !it.at.isAfter(now)) }
        val future = items.count { !isSent(it) && !allowFuture && it.at.isAfter(now) }
        val toSend = if (limit != null) due.take(limit) else due
        log.info(
            "PLAN: {} sales + {} ops · already sent {} · due now {} · held (future-dated) {} · this run sends {} · gap {}ms ≈ {}",
            sales.size,
            ops.size,
            items.count { isSent(it) },
            due.size,
            future,
            toSend.size,
            gapMs,
            fmt(toSend.size * gapMs),
        )
        parts.firstOrNull()?.let { log.info("  first sale: {}", ConnectMappersJson.snake(toSaleEvent(it))) }

        if (!live) {
            log.info("DRY-RUN (M8TRX_STREAM_LIVE!=true) — nothing sent, no state written.")
            summaryLine(date, seed, sales.size, ops.size, 0, 0, future, t0)
            return
        }

        Files.createDirectories(stateDir)
        if (!reused) writePlan(planFile, allocated)
        appendSwaps(swapsFile, guarded.fresh)
        val config = ConnectConfig.fromEnv()
        val driver = InboundPushDriver(WebhookClient(config), ConnectClient(config))
        var ok = 0
        var err = 0
        var streak = 0
        for ((i, item) in toSend.withIndex()) {
            val resp = when (item) {
                is SaleItem -> driver.pushSale(toSaleEvent(item.part), WebhookClient.AuthMode.API_KEY)

                is OpItem -> when (val b = item.body) {
                    is ShipmentManifest -> driver.pushShipment(b, WebhookClient.AuthMode.API_KEY)
                    is PricingUpdate -> driver.pushPricing(b, WebhookClient.AuthMode.API_KEY)
                    is ProductCatalogItem -> driver.pushCatalog(b, WebhookClient.AuthMode.API_KEY)
                    else -> error("unknown op ${b::class}")
                }
            }
            when (resp) {
                is ConnectResponse.Ok -> {
                    ok++
                    streak = 0
                    append(sentFile, item.id)
                    if (item is SaleItem) item.part.epcs.forEach { appendSold(soldLog, it) }
                    if (item is OpItem) {
                        item.churn?.let { PriceMemory.entryOf(item.id, item.at, item.store, it) }?.let { PriceMemory.record(memoryFile, it) }
                    }
                }

                is ConnectResponse.Err -> {
                    err++
                    streak++
                    log.error("  [{}] {} @{} → ERR {} {}", i + 1, item.id, item.store, resp.error.status, resp.error.code)
                    if (streak >= maxErrors) {
                        log.error("  {} consecutive refusals — stopping; re-run resumes from the ledger", streak)
                        break
                    }
                }
            }
            if ((i + 1) % 200 == 0) log.info("  … {}/{} sent ({} ok, {} err)", i + 1, toSend.size, ok, err)
            if (i < toSend.size - 1) Thread.sleep(gapMs)
        }
        log.info("dated stream done — ok={} err={} held={} runId={}", ok, err, future, runId)
        summaryLine(date, seed, sales.size, ops.size, ok, err, future, t0)
        if (err > 0) error("$err event(s) refused — see the log; the ledger holds what landed")
    }

    /** One machine-readable line for `status/SIM-RUN-LOG.md` (day.sh greps for it). */
    private fun summaryLine(date: LocalDate, seed: Long, sales: Int, ops: Int, ok: Int, err: Int, held: Int, t0: Long) {
        log.info(
            "SIM-RUN stream date={} seed={} sales={} ops={} base={} sent_ok={} sent_err={} held_future={} wall={}", date, seed, sales, ops,
            BaseCatalog.currencyFromEnv(), ok, err, held,
            fmt(
                System.currentTimeMillis() - t0,
            ),
        )
    }

    /**
     * Manifest lines for a restock: the day's sold quantities (keyed by whatever the caller counts: the stream keys by item
     * code, receiving by EAN), most-sold first (ties by key), each ROUNDED UP TO CASES OF 6. [maxLines] caps the list (the
     * old fixed top-5 is `M8TRX_DAY_MANIFEST_LINES=5`; the default is every line). ONE rule for the stream's
     * `shipment_manifest` and for [ReceiveStock], so what is received is what the manifest promised.
     */
    fun manifestLines(sold: Map<String, Int>, maxLines: Int = manifestMaxLines()): List<ShipmentLine> =
        sold.entries.filter { it.key.isNotBlank() && it.value > 0 }
            .sortedWith(compareBy({ -it.value }, { it.key }))
            .take(maxLines)
            .map { ShipmentLine(it.key, ((it.value + 5) / 6) * 6) }

    /** `M8TRX_DAY_MANIFEST_LINES`: cap on manifest lines per store-day; unset or 0 = every sold line. */
    fun manifestMaxLines(): Int = System.getenv("M8TRX_DAY_MANIFEST_LINES")?.toIntOrNull()?.takeIf { it > 0 } ?: Int.MAX_VALUE

    internal fun plannedOps(
        plans: List<StorePlan>,
        sales: List<PlannedSale>,
        chainDir: Path,
        seed: Long,
        runId: String,
        baseCurrency: String = BaseCatalog.currencyFromEnv(),
        stock: Map<String, List<EpcRow>> = emptyMap(),
    ): List<OpItem> {
        val base = BaseCatalog.of(chainDir, baseCurrency)
        val pricings = System.getenv("M8TRX_DAY_PRICINGS")?.toIntOrNull() ?: 2
        val catalogs = System.getenv("M8TRX_DAY_CATALOGS")?.toIntOrNull() ?: 1
        val siteIds = readSiteIds(chainDir.resolve("site_ids.csv"))
        val out = ArrayList<OpItem>()
        for (p in plans) {
            if (p.closed || p.open == null || p.close == null) continue
            val rng = Random(com.m8trx.twin.history.HistoryCsv.derive(seed, p.store, p.date, "ops"))
            val span = p.close.epochSecond - p.open.epochSecond
            fun at(): Instant = p.open.plusSeconds((span * rng.nextDouble()).toLong())
            val skus = loadAssortment(chainDir.resolve("stores/${p.store}/assortment.csv"), base)
            val byEan = skus.associateBy { it.ean }
            // Restock what sold: the day's sold units by item code, rounded up to cases of 6 - 30 min after open.
            // Counted from the ALLOCATED plan (the EPCs that actually sell, substitutions included), the same count
            // ReceiveStock reads, so the manifest and the receipt agree.
            val siteId = siteIds[p.store]
            if (siteId != null) {
                val itemCdByEpc = (stock[p.store] ?: loadEpcRows(chainDir.resolve("stores/${p.store}/epcs.csv"))).associate { it.epc to it.itemCd }
                val sold = sales.filter { it.store == p.store }.flatMap { it.epcs }.mapNotNull { itemCdByEpc[it] }
                    .filter { it.isNotBlank() }.groupingBy { it }.eachCount()
                val lines = manifestLines(sold)
                if (lines.isNotEmpty()) {
                    out +=
                        OpItem(
                            p.open.plusSeconds(1800),
                            "$runId-${p.store}-restock",
                            p.store,
                            "restock",
                            ShipmentManifest("$runId-${p.store}-restock", siteId, lines),
                        )
                }
            }
            if (skus.isNotEmpty()) {
                repeat(pricings) { k ->
                    val sk = skus[rng.nextInt(skus.size)]
                    // The one churn function: one factor moves the catalog's base-price update and the store's own price. Drawn
                    // before at(), the order the inline formula used, so a re-run of a date keeps its SKUs, times and ids.
                    val churn = churnFor(sk, rng)
                    out += OpItem(at(), "$runId-${p.store}-pricing-${k + 1}", p.store, "pricing", churn.update, churn)
                }
                repeat(catalogs) { k ->
                    val sk = byEan.values.elementAt(rng.nextInt(byEan.size))
                    out +=
                        OpItem(at(), "$runId-${p.store}-catalog-${k + 1}", p.store, "catalog", ProductCatalogItem(sk.itemCd, sk.name, gtin = sk.ean))
                }
            }
        }
        return out
    }

    /** What the day's sales will carry: priced from an update · at list · unpriced, and how many receipts split by price. */
    private fun logPriceCoverage(receipts: Int, parts: List<PricedPart>, remembered: Int, planned: Int) {
        val units = parts.groupBy { it.source }.mapValues { (_, l) -> l.sumOf { it.epcs.size } }
        val byCurrency = parts.groupingBy { it.currency ?: "none" }.eachCount().toSortedMap()
        log.info(
            "PRICES: {} receipts → {} sale events {} ({} split by price) · units at the last pricing_update {} · at list {} · unpriced {} · memory {} sent + {} planned updates",
            receipts,
            parts.size,
            byCurrency,
            parts.filter { it.id != it.sale.saleId }.map { it.sale.saleId }.distinct().size,
            units[PriceBook.Source.PRICING_UPDATE] ?: 0,
            units[PriceBook.Source.LIST] ?: 0,
            units[null] ?: 0,
            remembered,
            planned,
        )
    }

    /** EPCs held by OTHER dates' persisted plans — reserved even before they are sent, so two dates never share a unit. */
    private fun reservedByOtherPlans(stateDir: Path, own: Path): Set<String> {
        if (!Files.isDirectory(stateDir)) return emptySet()
        val ownSwaps = own.resolveSibling(own.fileName.toString().removeSuffix(".plan.csv") + ".swaps.csv")
        val files = Files.list(stateDir).use { it.toList() }
        val plans = files.filter { it.fileName.toString().endsWith(".plan.csv") && it != own }.flatMap { readPlan(it).flatMap { p -> p.epcs } }
        // an EPC swapped in for a back-room unit is spoken for between the choice and the send (once sent it is in the sold-log)
        val swapped = files.filter { it.fileName.toString().endsWith(".swaps.csv") && it != ownSwaps }
            .flatMap { readSwaps(it) }.map { it.new }.filter { it != DROPPED }
        return (plans + swapped).toSet()
    }

    internal fun writePlan(file: Path, sales: List<PlannedSale>) {
        Files.write(file, listOf("sale_id,store,occurred_at,epcs") + sales.map { "${it.saleId},${it.store},${it.at},${it.epcs.joinToString(";")}" })
    }

    fun readPlan(file: Path): List<PlannedSale> = Files.readAllLines(file).drop(1).filter { it.isNotBlank() }.map {
        val c = it.split(",")
        PlannedSale(c[0], c[1], Instant.parse(c[2]), c[3].split(";"))
    }

    internal fun readSiteIds(file: Path): Map<String, String> = if (!Files.exists(file)) {
        emptyMap()
    } else {
        Files.readAllLines(file).drop(1).mapNotNull { l ->
            l.split(",").takeIf { it.size >= 2 && it[0].isNotBlank() }?.let {
                it[0].trim() to
                    it[1].trim()
            }
        }.toMap()
    }

    private fun append(file: Path, line: String) {
        Files.writeString(file, "$line\n", StandardOpenOption.CREATE, StandardOpenOption.APPEND)
    }

    private fun fmt(ms: Long): String {
        val s = ms / 1000
        return "%dh%02dm%02ds".format(s / 3600, (s % 3600) / 60, s % 60)
    }
}

/** RFC-4180-ish splitter (quoted names carry commas). */
internal fun csvSplit(line: String): List<String> {
    val out = ArrayList<String>()
    val sb = StringBuilder()
    var q = false
    var i = 0
    while (i < line.length) {
        val ch = line[i]
        when {
            ch == '"' && q && i + 1 < line.length && line[i + 1] == '"' -> {
                sb.append('"')
                i++
            }

            ch == '"' -> q = !q

            ch == ',' && !q -> {
                out.add(sb.toString())
                sb.setLength(0)
            }

            else -> sb.append(ch)
        }
        i++
    }
    out.add(sb.toString())
    return out
}

/** Snake serialization for the dry-run log line (the webhook plane's casing). */
internal object ConnectMappersJson {
    fun snake(body: Any): String = com.m8trx.twin.connect.model.ConnectMappers.snake.writeValueAsString(body)
}
