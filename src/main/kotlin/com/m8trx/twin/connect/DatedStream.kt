/**
 * The DATED mode of `connectSaleStream` / `connectChainActivity` (BRIEF-TWIN-RECENT-WINDOW § 1.2) — on when
 * `M8TRX_STREAM_DATE` is set; without it both drivers behave exactly as before.
 *
 * A dated run streams ONE calendar day per store, generated by [RecentDay] (the history generator's own
 * store-day: operating model × story × seed), so the live days continue the year the dashboards already hold:
 *
 *  - **Volume** is the model's, per store, per day (Denver ≈ 250–290 transactions on an October weekday).
 *  - **`occurred_at`** is the transaction's own time — the shopper's exit from the store — so sales spread
 *    across the store's operating hours instead of landing as a burst at send time.
 *  - **One sale event per transaction**: `epc` for a one-unit basket, `epc_list` for the rest.
 *  - **Each EPC sells once.** Every basket line takes a unit of its own EAN from the store's `epcs.csv`,
 *    back-of-house (`BR-*`) first so the floor still looks stocked, never one already in the shared sold-log
 *    or reserved by another date's plan. A line whose EAN has no unit left is dropped and counted. The run
 *    prints each store's runway (units left ÷ today's units) — the brief's budget is ≥ 12 days.
 *  - **Resumable.** A live run persists its plan (`.twin-state/stream/<runId>.plan.csv`) and a sent ledger
 *    (`<runId>.sent`). A re-run of the same date and seed reuses the plan, skips what was sent, and sends
 *    what has come due — so a day can be streamed in two passes (Korea at 22:00 KST, the US stores the next
 *    afternoon) without a unit being sold twice or an id being re-used.
 *  - **Nothing in the future** is sent unless `M8TRX_STREAM_ALLOW_FUTURE=true`: the read windows are
 *    `[now-24h, now)`, so a future-dated sale reads as missing until the clock catches up.
 *  - **Chain mode only:** per store-day one restock manifest (what sold, rounded up to cases of 6) shortly
 *    after open, `M8TRX_DAY_PRICINGS` (2) price changes and `M8TRX_DAY_CATALOGS` (1) catalog re-asserts.
 *    ⚠ Those three payloads carry no event time in the §8 contract, so they land at SEND time.
 *
 * DRY-RUN unless `M8TRX_STREAM_LIVE=true` — the dated mode is new, so it is opt-in even though the undated
 * drivers fire on run. A dry run writes no state.
 *
 * Env: `M8TRX_STREAM_DATE` (yyyy-mm-dd) · `M8TRX_STREAM_SEED` (20261016, the history's) · `M8TRX_STREAM_STORES`
 * (csv; SaleStream default dec-us-denver, ChainActivity default all) · `M8TRX_STREAM_LIVE` (false) ·
 * `M8TRX_STREAM_ALLOW_FUTURE` (false) · `M8TRX_STREAM_GAP_MS` (120 → ≤ 8/s, under the measured ≤ 12 ceiling) ·
 * `M8TRX_STREAM_MAX_ERRORS` (5 consecutive refusals stop the run) · `M8TRX_STREAM_LIMIT` (send at most N
 * events — the warm-up) · `M8TRX_STREAM_SOLD_LOG` · `M8TRX_RUN_ID` (default `twin-day-<yyyymmdd>-<seed>`) ·
 * `M8TRX_CHAIN_DIR`.
 */
object DatedStream {
    private val log = LoggerFactory.getLogger("com.m8trx.twin.connect.DatedStream")

    data class EpcRow(val epc: String, val ean: String, val fixture: String, val itemCd: String = "") {
        val backOfHouse: Boolean get() = fixture.startsWith("BR-")
    }

    data class PlannedSale(val saleId: String, val store: String, val at: Instant, val epcs: List<String>)

    data class StorePlan(
        val store: String,
        val date: LocalDate,
        val closed: Boolean,
        val sales: List<PlannedSale>,
        val units: Int,
        val droppedLines: Int,
        val substitutedLines: Int,
        val fromBackOfHouse: Int,
        val unitsLeft: Int,
        val visits: Int,
        val revenueUsd: Double,
        val open: Instant?,
        val close: Instant?,
    ) {
        val runwayDays: Double get() = if (units == 0) Double.POSITIVE_INFINITY else unitsLeft.toDouble() / units
    }

    /** `epcs.csv` (epc,ean,item_cd,category,fixture,store_id) → rows, header dropped, blanks skipped. */
    fun loadEpcRows(file: Path): List<EpcRow> = Files.readAllLines(file).drop(1).mapNotNull { line ->
        val c = line.split(",")
        if (c.size < 6 || c[0].isBlank()) null else EpcRow(c[0].trim(), c[1].trim(), c[4].trim(), c[2].trim())
    }

    /** `assortment.csv` → EAN → (department, price_usd): what a substitute is matched on. */
    fun loadCatalog(file: Path): Map<String, Pair<String, Double>> {
        val lines = Files.readAllLines(file)
        val h = lines.first().split(",")
        val iEan = h.indexOf("ean")
        val iDept = h.indexOf("department")
        val iPrice = h.indexOf("price_usd")
        require(iEan >= 0 && iDept >= 0 && iPrice >= 0) { "$file lacks ean/department/price_usd" }
        return lines.drop(1).mapNotNull { l ->
            val c = csvSplit(l)
            val price = c.getOrNull(iPrice)?.toDoubleOrNull() ?: return@mapNotNull null
            c[iEan].trim() to (c[iDept].trim() to price)
        }.toMap()
    }

    /**
     * Allocate the day's baskets to real units. Pure and deterministic: queues per EAN, back-of-house first,
     * then the floor, each in EPC order; [exclude] (sold or reserved) never sells.
     *
     * The basket sampler concentrates on SKUs near the target line price, and a store holds 1–10 units of
     * each, so a busy day exhausts its favorites by mid-afternoon — 45 % of Denver's lines on 2026-10-10. A
     * line whose own EAN is out therefore takes the nearest-priced EAN **of the same department** that still
     * has a unit (a shopper buying the next tent over), keeping units per transaction and the department mix
     * intact; it is dropped only if the department is out. Substitutions are counted.
     */
    fun allocate(
        day: RecentDay.Day,
        rows: List<EpcRow>,
        exclude: Set<String>,
        runId: String,
        catalog: Map<String, Pair<String, Double>> = emptyMap(),
    ): StorePlan {
        val queues = rows.asSequence().filter { it.epc !in exclude }.distinctBy { it.epc }
            .sortedWith(compareBy({ !it.backOfHouse }, { it.epc }))
            .groupBy { it.ean }
            .mapValues { (_, rs) -> ArrayDeque(rs) }
        // department → EANs with stock, price-sorted (ties by EAN) — the substitute pool
        val pool: Map<String, MutableList<Pair<Double, String>>> = queues.keys.mapNotNull { e -> catalog[e]?.let { (d, p) -> Triple(d, p, e) } }
            .groupBy({ it.first }, { it.second to it.third })
            .mapValues { (_, l) -> l.sortedWith(compareBy({ it.first }, { it.second })).toMutableList() }
        fun take(ean: String): EpcRow? {
            val q = queues[ean] ?: return null
            val r = q.removeFirstOrNull()
            if (q.isEmpty()) catalog[ean]?.let { (d, p) -> pool[d]?.remove(p to ean) }
            return r
        }
        var dropped = 0
        var substituted = 0
        var boh = 0
        var units = 0
        val sales = ArrayList<PlannedSale>(day.txns.size)
        day.txns.forEachIndexed { i, t ->
            val epcs = t.lines.mapNotNull { line ->
                var r = take(line.ean)
                if (r == null) {
                    val sub = pool[line.department]?.minByOrNull { (p, _) -> kotlin.math.abs(p - line.priceUsd) }
                    if (sub != null) {
                        r = take(sub.second)
                        if (r != null) substituted++
                    }
                }
                if (r == null) {
                    dropped++
                } else if (r.backOfHouse) {
                    boh++
                }
                r?.epc
            }
            if (epcs.isNotEmpty()) {
                units += epcs.size
                sales += PlannedSale("$runId-${day.slug}-${"%04d".format(i + 1)}", day.slug, t.at, epcs)
            }
        }
        return StorePlan(
            store = day.slug,
            date = day.date,
            closed = false,
            sales = sales,
            units = units,
            droppedLines = dropped,
            substitutedLines = substituted,
            fromBackOfHouse = boh,
            unitsLeft = queues.values.sumOf { it.size },
            visits = day.visits,
            revenueUsd = day.cents / 100.0,
            open = day.open,
            close = day.close,
        )
    }

    /** The wire shape of one planned sale — `epc` for a single unit, `epc_list` otherwise; `occurred_at` is the transaction's time. */
    fun toSaleEvent(s: PlannedSale): SaleEvent = if (s.epcs.size == 1) {
        SaleEvent.byEpc(s.saleId, s.at.toString(), s.epcs.single())
    } else {
        SaleEvent.byEpcList(s.saleId, s.at.toString(), s.epcs)
    }

    // ── the run ───────────────────────────────────────────────────────────────

    private sealed interface Item {
        val at: Instant
        val id: String
        val store: String
    }

    private data class SaleItem(val s: PlannedSale) : Item {
        override val at get() = s.at
        override val id get() = s.saleId
        override val store get() = s.store
    }

    private data class OpItem(override val at: Instant, override val id: String, override val store: String, val kind: String, val body: Any) : Item

    fun run(defaultStores: List<String>, chainOps: Boolean) {
        val date = LocalDate.parse(System.getenv("M8TRX_STREAM_DATE"))
        val seed = System.getenv("M8TRX_STREAM_SEED")?.toLongOrNull() ?: RecentDay.HISTORY_SEED
        val live = System.getenv("M8TRX_STREAM_LIVE")?.toBooleanStrictOrNull() ?: false
        val allowFuture = System.getenv("M8TRX_STREAM_ALLOW_FUTURE")?.toBooleanStrictOrNull() ?: false
        val gapMs = System.getenv("M8TRX_STREAM_GAP_MS")?.toLongOrNull() ?: 120L
        val maxErrors = System.getenv("M8TRX_STREAM_MAX_ERRORS")?.toIntOrNull() ?: 5
        val limit = System.getenv("M8TRX_STREAM_LIMIT")?.toIntOrNull()
        val chainDir = Path.of(System.getenv("M8TRX_CHAIN_DIR")?.takeIf { it.isNotBlank() } ?: "reference/data/chain")
        val runId = System.getenv("M8TRX_RUN_ID")?.takeIf { it.isNotBlank() } ?: "twin-day-${date.format(DateTimeFormatter.BASIC_ISO_DATE)}-$seed"
        val soldLog = Path.of(System.getenv("M8TRX_STREAM_SOLD_LOG")?.takeIf { it.isNotBlank() } ?: ".twin-state/sold-epcs.txt")
        val stateDir = soldLog.parent?.resolve("stream") ?: Path.of(".twin-state/stream")
        val planFile = stateDir.resolve("$runId.plan.csv")
        val sentFile = stateDir.resolve("$runId.sent")
        val stores = System.getenv("M8TRX_STREAM_STORES")?.split(",")?.map { it.trim() }?.filter { it.isNotEmpty() } ?: defaultStores
        val t0 = System.currentTimeMillis()

        log.info(
            "═══ dated stream ═══ date={} seed={} stores={} chainOps={} live={} runId={}",
            date,
            seed,
            stores.size,
            chainOps,
            live,
            runId,
        )

        val recent = RecentDay(seed, chainDir)
        val priorSold = readPriorSold(soldLog)
        val reservedElsewhere = reservedByOtherPlans(stateDir, planFile)
        val reused = live && Files.exists(planFile)
        val plans: List<StorePlan> = stores.map { slug ->
            val day = recent.run(slug, date)
            if (day == null) {
                StorePlan(slug, date, true, emptyList(), 0, 0, 0, 0, 0, 0, 0.0, null, null)
            } else {
                allocate(
                    day,
                    loadEpcRows(chainDir.resolve("stores/$slug/epcs.csv")),
                    priorSold + reservedElsewhere,
                    runId,
                    loadCatalog(chainDir.resolve("stores/$slug/assortment.csv")),
                )
            }
        }
        val sales: List<PlannedSale> = if (reused) readPlan(planFile).filter { it.store in stores } else plans.flatMap { it.sales }
        if (reused) log.info("reusing the persisted plan {} ({} sales) — the allocation is frozen at first live run", planFile, sales.size)

        plans.forEach { p ->
            if (p.closed) {
                log.info("  {} CLOSED on {} (story holiday) — nothing to stream", p.store, p.date)
            } else {
                log.info(
                    "  {} txn={} units={} (BOH {}) substituted={} dropped={} visits={} revenue≈\${} hours {}..{} · units left {} → runway {} days",
                    p.store,
                    p.sales.size,
                    p.units,
                    p.fromBackOfHouse,
                    p.substitutedLines,
                    p.droppedLines,
                    p.visits,
                    "%.0f".format(p.revenueUsd),
                    p.open,
                    p.close,
                    p.unitsLeft,
                    "%.1f".format(p.runwayDays),
                )
            }
        }
        val lowRunway = plans.filter { !it.closed && it.runwayDays < 12.0 }
        if (lowRunway.isNotEmpty()) {
            log.warn(
                "  ⚠ runway under 12 days at today's rate: {}",
                lowRunway.map {
                    "${it.store}=${"%.1f".format(it.runwayDays)}"
                },
            )
        }

        val ops: List<OpItem> = if (chainOps) plannedOps(plans, sales, chainDir, seed, runId) else emptyList()
        val items: List<Item> = (sales.map { SaleItem(it) } + ops).sortedBy { it.at }
        val sent = if (Files.exists(sentFile)) Files.readAllLines(sentFile).map { it.trim() }.toSet() else emptySet()
        val now = Instant.now()
        val due = items.filter { it.id !in sent && (allowFuture || !it.at.isAfter(now)) }
        val future = items.count { it.id !in sent && !allowFuture && it.at.isAfter(now) }
        val toSend = if (limit != null) due.take(limit) else due
        log.info(
            "PLAN: {} sales + {} ops · already sent {} · due now {} · held (future-dated) {} · this run sends {} · gap {}ms ≈ {}",
            sales.size,
            ops.size,
            items.count { it.id in sent },
            due.size,
            future,
            toSend.size,
            gapMs,
            fmt(toSend.size * gapMs),
        )
        sales.firstOrNull()?.let { log.info("  first sale: {}", ConnectMappersJson.snake(toSaleEvent(it))) }

        if (!live) {
            log.info("DRY-RUN (M8TRX_STREAM_LIVE!=true) — nothing sent, no state written.")
            summaryLine(date, seed, sales.size, ops.size, 0, 0, future, t0)
            return
        }

        Files.createDirectories(stateDir)
        if (!reused) writePlan(planFile, sales)
        val config = ConnectConfig.fromEnv()
        val driver = InboundPushDriver(WebhookClient(config), ConnectClient(config))
        var ok = 0
        var err = 0
        var streak = 0
        for ((i, item) in toSend.withIndex()) {
            val resp = when (item) {
                is SaleItem -> driver.pushSale(toSaleEvent(item.s), WebhookClient.AuthMode.API_KEY)

                is OpItem -> when (val b = item.body) {
                    is ShipmentManifest -> driver.pushShipment(b, WebhookClient.AuthMode.API_KEY)
                    is PricingUpdate -> driver.pushPricing(b, WebhookClient.AuthMode.API_KEY)
                    is ProductCatalogItem -> driver.pushCatalog(b, WebhookClient.AuthMode.API_KEY)
                    else -> error("unknown op ${b::class}")
                }
            }
            when (resp) {
                is ConnectResponse.Ok -> {
                    ok++
                    streak = 0
                    append(sentFile, item.id)
                    if (item is SaleItem) item.s.epcs.forEach { appendSold(soldLog, it) }
                }

                is ConnectResponse.Err -> {
                    err++
                    streak++
                    log.error("  [{}] {} @{} → ERR {} {}", i + 1, item.id, item.store, resp.error.status, resp.error.code)
                    if (streak >= maxErrors) {
                        log.error("  {} consecutive refusals — stopping; re-run resumes from the ledger", streak)
                        break
                    }
                }
            }
            if ((i + 1) % 200 == 0) log.info("  … {}/{} sent ({} ok, {} err)", i + 1, toSend.size, ok, err)
            if (i < toSend.size - 1) Thread.sleep(gapMs)
        }
        log.info("dated stream done — ok={} err={} held={} runId={}", ok, err, future, runId)
        summaryLine(date, seed, sales.size, ops.size, ok, err, future, t0)
        if (err > 0) error("$err event(s) refused — see the log; the ledger holds what landed")
    }

    /** One machine-readable line for `status/SIM-RUN-LOG.md` (day.sh greps for it). */
    private fun summaryLine(date: LocalDate, seed: Long, sales: Int, ops: Int, ok: Int, err: Int, held: Int, t0: Long) {
        log.info(
            "SIM-RUN stream date={} seed={} sales={} ops={} sent_ok={} sent_err={} held_future={} wall={}", date, seed, sales, ops, ok, err, held,
            fmt(
                System.currentTimeMillis() - t0,
            ),
        )
    }

    /**
     * Manifest lines for a restock: the day's sold quantities (keyed by whatever the caller counts: the stream keys by item
     * code, receiving by EAN), most-sold first (ties by key), each ROUNDED UP TO CASES OF 6. [maxLines] caps the list (the
     * old fixed top-5 is `M8TRX_DAY_MANIFEST_LINES=5`; the default is every line). ONE rule for the stream's
     * `shipment_manifest` and for [ReceiveStock], so what is received is what the manifest promised.
     */
    fun manifestLines(sold: Map<String, Int>, maxLines: Int = manifestMaxLines()): List<ShipmentLine> =
        sold.entries.filter { it.key.isNotBlank() && it.value > 0 }
            .sortedWith(compareBy({ -it.value }, { it.key }))
            .take(maxLines)
            .map { ShipmentLine(it.key, ((it.value + 5) / 6) * 6) }

    /** `M8TRX_DAY_MANIFEST_LINES`: cap on manifest lines per store-day; unset or 0 = every sold line. */
    fun manifestMaxLines(): Int = System.getenv("M8TRX_DAY_MANIFEST_LINES")?.toIntOrNull()?.takeIf { it > 0 } ?: Int.MAX_VALUE

    private fun plannedOps(plans: List<StorePlan>, sales: List<PlannedSale>, chainDir: Path, seed: Long, runId: String): List<OpItem> {
        val pricings = System.getenv("M8TRX_DAY_PRICINGS")?.toIntOrNull() ?: 2
        val catalogs = System.getenv("M8TRX_DAY_CATALOGS")?.toIntOrNull() ?: 1
        val siteIds = readSiteIds(chainDir.resolve("site_ids.csv"))
        val out = ArrayList<OpItem>()
        for (p in plans) {
            if (p.closed || p.open == null || p.close == null) continue
            val rng = Random(com.m8trx.twin.history.HistoryCsv.derive(seed, p.store, p.date, "ops"))
            val span = p.close.epochSecond - p.open.epochSecond
            fun at(): Instant = p.open.plusSeconds((span * rng.nextDouble()).toLong())
            val skus = loadAssortment(chainDir.resolve("stores/${p.store}/assortment.csv"))
            val byEan = skus.associateBy { it.ean }
            // Restock what sold: the day's sold units by item code, rounded up to cases of 6 - 30 min after open.
            // Counted from the ALLOCATED plan (the EPCs that actually sell, substitutions included), the same count
            // ReceiveStock reads, so the manifest and the receipt agree.
            val siteId = siteIds[p.store]
            if (siteId != null) {
                val itemCdByEpc = loadEpcRows(chainDir.resolve("stores/${p.store}/epcs.csv")).associate { it.epc to it.itemCd }
                val sold = sales.filter { it.store == p.store }.flatMap { it.epcs }.mapNotNull { itemCdByEpc[it] }
                    .filter { it.isNotBlank() }.groupingBy { it }.eachCount()
                val lines = manifestLines(sold)
                if (lines.isNotEmpty()) {
                    out +=
                        OpItem(
                            p.open.plusSeconds(1800),
                            "$runId-${p.store}-restock",
                            p.store,
                            "restock",
                            ShipmentManifest("$runId-${p.store}-restock", siteId, lines),
                        )
                }
            }
            if (skus.isNotEmpty()) {
                repeat(pricings) { k ->
                    val sk = skus[rng.nextInt(skus.size)]
                    val churned = (sk.priceMinor * (0.7 + rng.nextDouble() * 0.5)).toLong().coerceAtLeast(1)
                    out += OpItem(at(), "$runId-${p.store}-pricing-${k + 1}", p.store, "pricing", PricingUpdate(sk.itemCd, churned, gtin = sk.ean))
                }
                repeat(catalogs) { k ->
                    val sk = byEan.values.elementAt(rng.nextInt(byEan.size))
                    out +=
                        OpItem(at(), "$runId-${p.store}-catalog-${k + 1}", p.store, "catalog", ProductCatalogItem(sk.itemCd, sk.name, gtin = sk.ean))
                }
            }
        }
        return out
    }

    /** EPCs held by OTHER dates' persisted plans — reserved even before they are sent, so two dates never share a unit. */
    private fun reservedByOtherPlans(stateDir: Path, own: Path): Set<String> {
        if (!Files.isDirectory(stateDir)) return emptySet()
        return Files.list(stateDir).use { s ->
            s.filter { it.fileName.toString().endsWith(".plan.csv") && it != own }.toList()
        }.flatMap { readPlan(it).flatMap { p -> p.epcs } }.toSet()
    }

    private fun writePlan(file: Path, sales: List<PlannedSale>) {
        Files.write(file, listOf("sale_id,store,occurred_at,epcs") + sales.map { "${it.saleId},${it.store},${it.at},${it.epcs.joinToString(";")}" })
    }

    fun readPlan(file: Path): List<PlannedSale> = Files.readAllLines(file).drop(1).filter { it.isNotBlank() }.map {
        val c = it.split(",")
        PlannedSale(c[0], c[1], Instant.parse(c[2]), c[3].split(";"))
    }

    internal fun readSiteIds(file: Path): Map<String, String> = if (!Files.exists(file)) {
        emptyMap()
    } else {
        Files.readAllLines(file).drop(1).mapNotNull { l ->
            l.split(",").takeIf { it.size >= 2 && it[0].isNotBlank() }?.let {
                it[0].trim() to
                    it[1].trim()
            }
        }.toMap()
    }

    private fun append(file: Path, line: String) {
        Files.writeString(file, "$line\n", StandardOpenOption.CREATE, StandardOpenOption.APPEND)
    }

    private fun fmt(ms: Long): String {
        val s = ms / 1000
        return "%dh%02dm%02ds".format(s / 3600, (s % 3600) / 60, s % 60)
    }
}

/** RFC-4180-ish splitter (quoted names carry commas). */
internal fun csvSplit(line: String): List<String> {
    val out = ArrayList<String>()
    val sb = StringBuilder()
    var q = false
    var i = 0
    while (i < line.length) {
        val ch = line[i]
        when {
            ch == '"' && q && i + 1 < line.length && line[i + 1] == '"' -> {
                sb.append('"')
                i++
            }

            ch == '"' -> q = !q

            ch == ',' && !q -> {
                out.add(sb.toString())
                sb.setLength(0)
            }

            else -> sb.append(ch)
        }
        i++
    }
    out.add(sb.toString())
    return out
}

/** Snake serialization for the dry-run log line (the webhook plane's casing). */
internal object ConnectMappersJson {
    fun snake(body: Any): String = com.m8trx.twin.connect.model.ConnectMappers.snake.writeValueAsString(body)
}
