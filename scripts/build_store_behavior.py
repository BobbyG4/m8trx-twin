#!/usr/bin/env python3
"""
Neutral behavior parameters for the nine non-Denver stores, generated from Denver's tuned file (slice 2b).

    python3 scripts/build_store_behavior.py            # writes reference/data/behavior/<slug>.json for the nine
    python3 scripts/build_store_behavior.py --check    # exit 1 if a committed file differs from what this would write

Reads : reference/data/behavior/dec-us-denver.json (never written), stores/<slug>/model/{profile,fixtures}.json.
Writes: reference/data/behavior/<slug>.json for every chain store except Denver. Offline, stdlib only, deterministic.

"Neutral" means the six truths of TWIN-REQ-007 requirement 10 are SWITCHED OFF (every multiplier 1.0, the hero appeal 1.0 and no hero
styles), so the stores' only differences are their layout, assortment, size and calendar; Denver's tuned truths stay Denver's. The
structural numbers (levels per fixture, eye level, the size-run break share, the colour-story thresholds) stay, because they say
where a truth would apply, not how strongly. Everything else (personas, stops, dwell, try-on, buy chances, the day-of-week shape)
is Denver's. The seed is Denver's plus the store's serial index (the store-day's per-store EPC slice).
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BEH = os.path.join(ROOT, "reference/data/behavior")
CHAIN = os.path.join(ROOT, "reference/data/chain/stores")
DENVER = "dec-us-denver"
# must match StoreState.STORE_SLUGS (the serial slices)
SLUGS = [DENVER, "dec-fr-bordeaux", "dec-fr-lille", "dec-fr-lyon", "dec-fr-marseille", "dec-fr-paris", "dec-kr-busan", "dec-kr-seoul",
         "dec-us-nyc", "dec-us-sf"]
NEUTRAL = {"entrance_table_impressions": 1.0, "entrance_table_pickup": 1.0, "back_corner_impressions": 1.0, "eye_level_pickup": 1.0,
           "floor_level_pickup": 1.0, "size_run_conversion": 1.0, "color_story_coherent": 1.0, "color_story_clash": 1.0,
           "adjacency_complement": 1.0}


def jdump(o):
    return json.dumps(o, indent=2, ensure_ascii=False) + "\n"


def build(slug, denver):
    prof = json.load(open(os.path.join(CHAIN, slug, "model/profile.json"), encoding="utf-8"))
    fx = json.load(open(os.path.join(CHAIN, slug, "model/fixtures.json"), encoding="utf-8"))["fixtures"]
    d = json.loads(json.dumps(denver))
    d["_doc"] = ("NEUTRAL behavior parameters for " + slug + ", generated by scripts/build_store_behavior.py from Denver's tuned file. "
                 "The six truths are OFF (multipliers 1.0, no hero styles); every other number is Denver's. Do not edit by hand: edit "
                 "the generator, or copy this file and tune the copy. " + d["_doc"])
    d["site"] = slug
    d["timezone"] = prof["timezone"]
    d["seed"] = denver["seed"] + SLUGS.index(slug)
    for k, v in NEUTRAL.items():
        d["truths"][k] = v
    d["truths"]["_neutral_doc"] = "Every multiplier above is 1.0: the truth is off for this store. Denver's file carries the tuned values."
    d["content"]["hero_appeal"] = 1.0
    d["content"]["heroes"] = []
    floor = sorted(c for c, v in fx.items() if v.get("space") == "sales_floor" and v.get("zone_type") == "fixture" and v.get("levels"))
    islands = [c for c in floor if fx[c]["fixture_category"] == "promo_island"]
    gond = [c for c in floor if fx[c]["fixture_category"] in ("gondola_front", "gondola_back")]
    d["reset"] = {
        "_doc": "Neutral stores run no scripted reset; these are this store's own codes so the names resolve.",
        "hero_back_corner_fixture": gond[-1], "entrance_table_fixture": (islands or floor)[0], "complement_handles": [],
        "control_fixture": gond[len(gond) // 2],
    }
    return jdump(d)


def main():
    denver = json.load(open(os.path.join(BEH, DENVER + ".json"), encoding="utf-8"))
    bad = []
    for slug in SLUGS[1:]:
        text = build(slug, denver)
        path = os.path.join(BEH, slug + ".json")
        if "--check" in sys.argv:
            if not os.path.exists(path) or open(path, encoding="utf-8").read() != text:
                bad.append(slug)
        else:
            with open(path, "w", encoding="utf-8", newline="") as f:
                f.write(text)
            print("wrote", os.path.relpath(path, ROOT))
    if bad:
        print("stale: " + ", ".join(bad))
        sys.exit(1)


if __name__ == "__main__":
    main()
